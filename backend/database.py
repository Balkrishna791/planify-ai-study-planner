"""Small database adapter for local SQLite and production PostgreSQL.

The application deliberately keeps SQL in one portable subset. SQLite remains the
zero-cost local/test default; setting DATABASE_URL or PLANIFY_DATABASE_URL switches
production to PostgreSQL without storing data on the web-service filesystem.
"""

import os
import re
import sqlite3

import psycopg2
from psycopg2.extras import RealDictCursor


DATABASE_ERRORS = (sqlite3.Error, psycopg2.Error)
DATABASE_OPERATIONAL_ERRORS = (sqlite3.OperationalError, psycopg2.OperationalError, psycopg2.ProgrammingError)
DATABASE_INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg2.IntegrityError)


def configured_database_url():
    """Return a normalized PostgreSQL URL, or None when using SQLite locally."""
    url = (os.environ.get("PLANIFY_DATABASE_URL") or os.environ.get("DATABASE_URL") or "").strip()
    if url.startswith("postgres://"):
        return "postgresql://" + url[len("postgres://"):]
    if url.startswith("postgresql://") or url.startswith("postgresql+psycopg2://"):
        return url.replace("postgresql+psycopg2://", "postgresql://", 1)
    return None


def _translate_postgres_sql(query):
    """Translate the tiny SQLite-only SQL dialect used by the legacy app."""
    translated = query.strip()
    translated = re.sub(
        r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        translated,
        flags=re.IGNORECASE,
    )
    translated = re.sub(
        r"^(\s*ALTER\s+TABLE\s+[^\s]+\s+ADD\s+COLUMN\s+)",
        r"\1IF NOT EXISTS ",
        translated,
        flags=re.IGNORECASE,
    )
    ignore_match = re.match(r"^(\s*)INSERT\s+OR\s+IGNORE\s+", translated, flags=re.IGNORECASE)
    if ignore_match:
        translated = re.sub(r"^\s*INSERT\s+OR\s+IGNORE\s+", "INSERT ", translated, count=1, flags=re.IGNORECASE)
        translated = translated.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    # Planify uses qmark parameters with values supplied separately. None of its
    # SQL strings contain literal question marks, so this is intentionally narrow.
    return translated.replace("?", "%s")


class PostgresCursor:
    def __init__(self, connection, cursor):
        self._connection = connection
        self._cursor = cursor

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    @property
    def lastrowid(self):
        """Compatibility for the three existing insert sites that need an ID."""
        cursor = self._connection._raw.cursor()
        try:
            cursor.execute("SELECT LASTVAL()")
            return cursor.fetchone()[0]
        finally:
            cursor.close()


class PostgresConnection:
    """Expose the SQLite-shaped interface used by the existing Flask handlers."""
    is_postgres = True

    def __init__(self, database_url):
        self._raw = psycopg2.connect(database_url)

    def execute(self, query, params=()):
        cursor = self._raw.cursor(cursor_factory=RealDictCursor)
        cursor.execute(_translate_postgres_sql(query), params)
        return PostgresCursor(self, cursor)

    def executescript(self, script):
        # Schema/index scripts contain only independent DDL statements.
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)

    def commit(self):
        self._raw.commit()

    def rollback(self):
        self._raw.rollback()

    def close(self):
        self._raw.close()


def connect(sqlite_path):
    """Connect to PostgreSQL when configured, otherwise use the local SQLite DB."""
    database_url = configured_database_url()
    if database_url:
        return PostgresConnection(database_url)
    conn = sqlite3.connect(sqlite_path)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    conn.execute("PRAGMA busy_timeout = 5000")
    return conn
