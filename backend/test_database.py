import os
import unittest
from unittest.mock import patch

from backend import database


class DatabaseCompatibilityTests(unittest.TestCase):
    def test_database_url_prefers_planify_setting_and_normalizes_legacy_scheme(self):
        with patch.dict(os.environ, {
            'PLANIFY_DATABASE_URL': 'postgres://user:secret@db.example/planify',
            'DATABASE_URL': 'postgresql://ignored.example/other',
        }, clear=False):
            self.assertEqual(
                database.configured_database_url(),
                'postgresql://user:secret@db.example/planify',
            )

    def test_database_url_is_none_for_local_sqlite_configuration(self):
        with patch.dict(os.environ, {
            'PLANIFY_DATABASE_URL': '', 'DATABASE_URL': '',
        }, clear=False):
            self.assertIsNone(database.configured_database_url())

    def test_postgres_translation_preserves_parameters_and_converts_identity(self):
        query = 'CREATE TABLE students (student_id INTEGER PRIMARY KEY AUTOINCREMENT, email TEXT WHERE owner=?)'
        translated = database._translate_postgres_sql(query)
        self.assertIn('student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', translated)
        self.assertIn('owner=%s', translated)

    def test_postgres_translation_converts_insert_or_ignore(self):
        translated = database._translate_postgres_sql('INSERT OR IGNORE INTO topics (subject_id) VALUES (?)')
        self.assertEqual(translated, 'INSERT INTO topics (subject_id) VALUES (%s) ON CONFLICT DO NOTHING')

    def test_postgres_translation_makes_legacy_column_migrations_idempotent(self):
        translated = database._translate_postgres_sql("ALTER TABLE students ADD COLUMN education_level TEXT DEFAULT ''")
        self.assertEqual(translated, "ALTER TABLE students ADD COLUMN IF NOT EXISTS education_level TEXT DEFAULT ''")

